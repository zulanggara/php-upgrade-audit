<?php
/**
 * Regenerate scripts/null_params.php: for every internal function, the positions of parameters that take a
 * scalar (bool/int/float/string, alone or in a union) and do not allow null. Passing null there is deprecated
 * since PHP 8.1 (RFC deprecate_null_to_scalar_internal_arg). Run on the newest PHP, with as many extensions
 * loaded as possible, and with the php-src stubs of that release for the extensions that are not loaded:
 *   git clone --depth 1 --branch PHP-8.5.12 --filter=blob:none --sparse https://github.com/php/php-src.git
 *   (cd php-src && git sparse-checkout set --no-cone '*.stub.php')
 *   php tests/gen_null_params.php php-src > scripts/null_params.php
 * The scanner merges this list with the same reflection on the PHP that runs it.
 */
declare(strict_types=1);

const SCALAR = ['bool', 'int', 'float', 'string', 'true', 'false'];
$out = [];
foreach (get_defined_functions()['internal'] as $fn) {
    $pos = nullRejectingScalars(new ReflectionFunction($fn));
    if ($pos !== []) {
        $out[strtolower($fn)] = $pos;
    }
}
// Constructors ("new:class") and static methods ("class::method") of internal classes: the calls a scanner can
// tie to a class without knowing variable types.
foreach (array_merge(get_declared_classes(), get_declared_interfaces()) as $cls) {
    $rc = new ReflectionClass($cls);
    if (!$rc->isInternal()) {
        continue;
    }
    foreach ($rc->getMethods() as $m) {
        if ($m->getDeclaringClass()->getName() !== $rc->getName() && !$m->isConstructor()) {
            continue;
        }
        $key = $m->isConstructor() ? 'new:' . strtolower($cls) : ($m->isStatic() ? strtolower($cls) . '::' . strtolower($m->getName()) : null);
        if ($key !== null && ($pos = nullRejectingScalars($m)) !== []) {
            $out[$key] = $pos;
        }
    }
}
$fromStubs = 0;
if (isset($argv[1]) && is_dir($argv[1])) {
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($argv[1], FilesystemIterator::SKIP_DOTS));
    foreach ($it as $f) {
        if (str_ends_with($f->getFilename(), '.stub.php') && !str_contains($f->getPathname(), '/tests/')) {
            foreach (stubFunctions((string) file_get_contents($f->getPathname())) as $fn => $pos) {
                $known = str_contains($fn, ':') ? class_exists(preg_replace('/^new:|::.*$/', '', $fn), false) : function_exists($fn);
                if (!isset($out[$fn]) && !$known && $pos !== []) {
                    $out[$fn] = $pos;
                    $fromStubs++;
                }
            }
        }
    }
}
ksort($out);
$exts = get_loaded_extensions();
sort($exts);
echo "<?php\n/**\n * Generated by tests/gen_null_params.php on PHP " . PHP_VERSION . " (" . count($out) . " entries, $fromStubs of them from the php-src stubs; loaded extensions: "
    . wordwrap(implode(', ', $exts), 100, "\n * ") . ").\n"
    . " * Key => 0-based positions of scalar parameters that do not accept null. Keys: function, \"new:class\"\n * (constructor), \"class::method\" (static method); names lowercase, classes with their namespace.\n */\nreturn [\n";
foreach ($out as $fn => $pos) {
    echo "    '$fn' => [" . implode(', ', $pos) . "],\n";
}
echo "];\n";

/** @return list<int> */
function nullRejectingScalars(ReflectionFunctionAbstract $f): array
{
    $pos = [];
    foreach ($f->getParameters() as $p) {
        $t = $p->getType();
        if ($t === null || $t->allowsNull() || $p->isPassedByReference() || $p->isVariadic()) {
            continue;
        }
        $names = $t instanceof ReflectionUnionType ? array_map(fn ($x) => $x->getName(), $t->getTypes()) : [$t instanceof ReflectionNamedType ? $t->getName() : ''];
        if (array_intersect($names, SCALAR) !== []) {
            $pos[] = $p->getPosition();
        }
    }
    return $pos;
}

/**
 * Global functions declared in a php-src stub file, with the positions of scalar parameters that reject null.
 * @return array<string, list<int>>
 */
function stubFunctions(string $code): array
{
    $t = array_values(array_filter(token_get_all($code), fn ($x) => !is_array($x) || !in_array($x[0], [T_WHITESPACE, T_COMMENT, T_DOC_COMMENT], true)));
    $out = [];
    $stack = [];        // per open brace: the namespace it opens ('' = global), or false for any other block
    $fileNs = '';       // "namespace Foo;" without braces
    $nextBrace = false; // the next "{" opens a namespace block with this name
    $n = count($t);
    for ($i = 0; $i < $n; $i++) {
        $x = $t[$i];
        if ($x === '{' || (is_array($x) && in_array($x[0], [T_CURLY_OPEN, T_DOLLAR_OPEN_CURLY_BRACES], true))) {
            $stack[] = $nextBrace;
            $nextBrace = false;
            continue;
        }
        if ($x === '}') { array_pop($stack); continue; }
        if (is_array($x) && $x[0] === T_NAMESPACE) {
            $name = is_array($t[$i + 1]) && in_array($t[$i + 1][0], [T_STRING, T_NAME_QUALIFIED], true) ? $t[$i + 1][1] : '';
            if (($t[$i + ($name === '' ? 1 : 2)] ?? null) === '{') {
                $nextBrace = $name;
            } else {
                $fileNs = $name;
            }
            continue;
        }
        $nsBraces = array_filter($stack, fn ($b) => is_string($b) && !str_starts_with($b, 'class:'));
        $ns = $fileNs !== '' ? $fileNs : (string) (end($nsBraces) ?: '');
        $others = count(array_filter($stack, fn ($b) => $b === false));
        if (is_array($x) && in_array($x[0], [T_CLASS, T_INTERFACE, T_ENUM, T_TRAIT], true) && is_array($t[$i + 1]) && $t[$i + 1][0] === T_STRING && $others === 0) {
            $class = strtolower(($ns !== '' ? $ns . '\\' : '') . $t[$i + 1][1]);
            for ($j = $i; $j < $n && $t[$j] !== '{'; $j++);
            $stack[] = 'class:' . $class;
            $i = $j;
            continue;
        }
        if (!is_array($x) || $x[0] !== T_FUNCTION || !is_array($t[$i + 1]) || $t[$i + 1][0] !== T_STRING) {
            continue;
        }
        $top = end($stack);
        $inClass = is_string($top) && str_starts_with($top, 'class:') && $others === 0;
        if ($inClass) {
            $static = false;
            for ($b = $i - 1; $b >= 0 && is_array($t[$b]) && in_array($t[$b][0], [T_PUBLIC, T_PROTECTED, T_PRIVATE, T_STATIC, T_FINAL, T_ABSTRACT], true); $b--) {
                $static = $static || $t[$b][0] === T_STATIC;
                $public = ($public ?? true) && !in_array($t[$b][0], [T_PROTECTED, T_PRIVATE], true);
            }
            $method = strtolower($t[$i + 1][1]);
            $prefix = $method === '__construct' ? 'new:' . substr($top, 6) : ($static ? substr($top, 6) . '::' . $method : null);
            unset($public);
        } elseif ($ns !== '' || $others > 0 || array_filter($stack, fn ($b) => is_string($b) && str_starts_with($b, 'class:')) !== []) {
            continue;
        }
        $name = $inClass ? $prefix : strtolower($t[$i + 1][1]);
        if ($name === null) {
            continue;
        }
        $j = $i + 3; // after "("
        $pos = [];
        $param = 0;
        $cur = [];
        $pd = 0;
        for (; $j < $n; $j++) {
            $y = $t[$j];
            if ($y === '(' || $y === '[') { $pd++; }
            if (($y === ')' || $y === ']') && $pd > 0) { $pd--; $cur[] = $y; continue; }
            if ($pd === 0 && ($y === ',' || $y === ')')) {
                if ($cur !== [] && rejectsNull($cur)) {
                    $pos[] = $param;
                }
                if ($cur !== []) { $param++; }
                $cur = [];
                if ($y === ')') { break; }
                continue;
            }
            $cur[] = $y;
        }
        $out[$name] = $pos;
        $i = $j;
    }
    return $out;
}

/** One stub parameter (its tokens): a scalar type that does not allow null, not by reference, not variadic. */
function rejectsNull(array $tokens): bool
{
    $type = [];
    $default = null;
    // Drop attributes such as #[\SensitiveParameter].
    $clean = [];
    $attr = 0;
    foreach ($tokens as $y) {
        if (is_array($y) && $y[0] === T_ATTRIBUTE) { $attr++; continue; }
        if ($attr > 0) { if ($y === '[') { $attr++; } elseif ($y === ']') { $attr--; } continue; }
        $clean[] = $y;
    }
    $tokens = $clean;
    foreach ($tokens as $k => $y) {
        $v = is_array($y) ? $y[1] : $y;
        if (is_array($y) && $y[0] === T_VARIABLE) {
            $rest = array_slice($tokens, $k + 1);
            if ($rest !== [] && $rest[0] === '=') {
                $default = strtolower(implode('', array_map(fn ($z) => is_array($z) ? $z[1] : $z, array_slice($rest, 1))));
            }
            break;
        }
        if ($v === '&' || (is_array($y) && in_array($y[0], [T_ELLIPSIS, T_AMPERSAND_FOLLOWED_BY_VAR_OR_VARARG, T_AMPERSAND_NOT_FOLLOWED_BY_VAR_OR_VARARG], true))) {
            return false;
        }
        $type[] = strtolower($v);
    }
    $names = preg_split('/[|&()]/', implode('', $type), -1, PREG_SPLIT_NO_EMPTY);
    if ($names === [] || str_starts_with(implode('', $type), '?') || array_intersect($names, ['null', 'mixed']) !== [] || $default === 'null') {
        return false;
    }
    return array_intersect($names, SCALAR) !== [];
}
